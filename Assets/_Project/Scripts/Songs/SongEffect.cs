namespace PiperToy
{
    /// <summary>What a song does to the rats that hear it. Each one copies a song from the old game.</summary>
    public enum SongEffect
    {
        /// <summary>Charms every rat nearby, so they follow the Piper.</summary>
        Dance,

        /// <summary>The rats walk in a line behind the Piper.</summary>
        Conga,

        /// <summary>The rats stand in a heart around the Piper.</summary>
        Heart,

        /// <summary>The rats spin round and round in flashing colors.</summary>
        Disco,

        /// <summary>The rats swell up, float away on the wind and pop.</summary>
        Balloons,

        /// <summary>The rats follow, hopping and singing.</summary>
        Choir,

        /// <summary>The rats follow and lift the Piper up.</summary>
        CrowdSurf,

        /// <summary>The rats roll over and play dead for a while.</summary>
        Faint,
    }
}
